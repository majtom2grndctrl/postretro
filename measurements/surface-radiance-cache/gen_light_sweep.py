#!/usr/bin/env python3
"""Emit a sealed single-hall .map with an a x b grid of static point lights.

The geometry (hall plus a 3x3 pillar field for occlusion) is identical at every
light count; only the light grid changes, so patch and probe counts are fixed
and the sweep isolates light scaling.

usage: gen_light_sweep.py <cols> <rows> <out.map> [--size 1536] [--height 256]
"""
import argparse

TEX = "50-free-textures/concrete_stone_021"


def box(x0, y0, z0, x1, y1, z1, tex=TEX):
    f = lambda *p: "( %d %d %d )" % p
    sides = [
        (f(x0, y1, z0), f(x0, y0, z1), f(x0, y0, z0)),
        (f(x0, y0, z0), f(x1, y0, z1), f(x1, y0, z0)),
        (f(x0, y0, z0), f(x1, y1, z0), f(x0, y1, z0)),
        (f(x0, y1, z1), f(x1, y0, z1), f(x0, y0, z1)),
        (f(x1, y1, z0), f(x0, y1, z1), f(x0, y1, z0)),
        (f(x1, y0, z0), f(x1, y1, z1), f(x1, y1, z0)),
    ]
    return "{\n" + "".join("%s %s %s %s 0 0 0 1 1\n" % (a, b, c, tex) for a, b, c in sides) + "}\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cols", type=int)
    ap.add_argument("rows", type=int)
    ap.add_argument("out")
    ap.add_argument("--size", type=int, default=1536)
    ap.add_argument("--height", type=int, default=256)
    ap.add_argument("--tex", default=TEX)
    ap.add_argument("--color", default="255 240 220")
    ap.add_argument("--intensity", type=int, default=150)
    ap.add_argument("--falloff", type=int, default=300)
    ap.add_argument("--pillars", type=int, default=3)
    ap.add_argument("--fill", default=None, help="worldspawn _bounce_fill value (omit for the compiler default)")
    a = ap.parse_args()
    S, H, T = a.size, a.height, 16
    out = ['// Game: Postretro', '// Format: Standard',
           '// Generated by gen_light_sweep.py %d %d' % (a.cols, a.rows),
           '// entity 0', '{', '"classname" "worldspawn"', '"wad" ""', '"_tb_mod" "dev"']
    if a.fill is not None:
        out.append('"_bounce_fill" "%s"' % a.fill)
    brushes = [
        box(-T, -T, -T, S + T, S + T, 0, a.tex),          # floor
        box(-T, -T, H, S + T, S + T, H + T, a.tex),       # ceiling
        box(-T, -T, 0, 0, S + T, H, a.tex),               # -x wall
        box(S, -T, 0, S + T, S + T, H, a.tex),            # +x wall
        box(0, -T, 0, S, 0, H, a.tex),                    # -y wall
        box(0, S, 0, S, S + T, H, a.tex),                 # +y wall
    ]
    p, pw = a.pillars, 64
    for i in range(p):
        for j in range(p):
            cx = int(S * (i + 0.5) / p)
            cy = int(S * (j + 0.5) / p)
            brushes.append(box(cx - pw // 2, cy - pw // 2, 0, cx + pw // 2, cy + pw // 2, H, a.tex))
    for n, b in enumerate(brushes):
        out.append("// brush %d" % n)
        out.append(b.rstrip("\n"))
    out.append("}")
    k = 0
    for i in range(a.cols):
        for j in range(a.rows):
            x = int(S * (i + 0.5) / a.cols) + 7  # offset off pillar centres
            y = int(S * (j + 0.5) / a.rows) + 11
            out += ["// entity %d" % (k + 1), "{", '"classname" "light"',
                    '"origin" "%d %d %d"' % (x, y, H - 40),
                    '"_color" "%s"' % a.color, '"_falloff_range" "%d"' % a.falloff,
                    '"_bake_only" "0"', '"delay" "0"', '"light" "%d"' % a.intensity,
                    '"_shadow_type" "static_light_map"', "}"]
            k += 1
    out += ["// entity %d" % (k + 1), "{", '"classname" "info_player_start"',
            '"origin" "%d %d 32"' % (S // 6, S // 6), "}"]
    open(a.out, "w").write("\n".join(out) + "\n")
    print("%s: %d lights, %d brushes" % (a.out, k, len(brushes)))


main()
