//! The two documents the SDK bundle generates: its quickstart README and the
//! `postretro.toml` that makes the bundle root a starter project.
//!
//! See: context/lib/build_pipeline.md §Distribution packaging (§SDK bundle)

use crate::binaries::binary_name;
use crate::manifest::Manifest;

use super::{BIN_DIR, RELEASE_ENGINE_STEM, SDK_BUNDLE_NAME, STARTER_MOD, STARTER_TEMPLATE};

/// Render the bundle's own project marker: the package is the bundle's name
/// and the mod is the empty starter. It carries no recipes, since the starter
/// declares no levels.
///
/// The rendered text is re-parsed before it is returned, so a marker the tool
/// itself cannot open fails the run here rather than on the recipient's
/// machine.
pub(super) fn render_bundle_manifest() -> Result<String, String> {
    let rendered = format!(
        "# Generated by `postretro-tool sdk-dist`. This bundle root is a starter\n\
         # Postretro project: its presence is what lets `bin/postretro-tool run`\n\
         # and `bin/postretro-tool dist` find the tree they are standing in.\n\
         # Rename `name` before you release anything built from it.\n\
         [package]\n\
         name = \"{SDK_BUNDLE_NAME}\"\n\
         mod = \"{STARTER_MOD}\"\n"
    );
    Manifest::parse(&rendered).map_err(|error| {
        format!(
            "sdk-dist: the generated bundle {}: {error}\n\n{rendered}",
            crate::project::MARKER_FILE
        )
    })?;
    Ok(rendered)
}

/// Render the quickstart README shipped at the bundle root.
pub(super) fn render_readme() -> String {
    let engine_binary = binary_name("postretro");
    let prl_build = binary_name("prl-build");
    let scripts_build = binary_name("scripts-build");
    let tool = binary_name("postretro-tool");
    let release_engine = binary_name(RELEASE_ENGINE_STEM);
    let mod_root = format!("content/{STARTER_MOD}");
    format!(
        "# Postretro SDK\n\
\n\
This is the Postretro engine and its content tools. It ships **no game\n\
content**: you bring your own maps, textures, models and scripts. It holds the\n\
level and script compilers, the content tool, the SDK definitions, the\n\
human-facing docs, the asset tools, a debug/hot-reload authoring engine, and an\n\
optimized engine for the games you ship.\n\
\n\
The bundle root is also a small **starter project**: `postretro.toml` marks it,\n\
and `{mod_root}/` is an empty mod — an entry script that declares a name and\n\
nothing else, and an empty `maps/`. Its package is `{SDK_BUNDLE_NAME}`, so runs\n\
from it keep their settings and saves under that name. On macOS and Linux the\n\
directory name is the platform's normalized form of it; see \"Where player data\n\
lives\" in `docs/distribution.md` for the exact directory.\n\
\n\
## Host-native caveat\n\
\n\
This bundle is **host-native**: the binaries were compiled for the operating\n\
system this bundle was built on and link native C/C++ dependencies. Run it on\n\
that same OS. To build for another platform, use a bundle built there.\n\
\n\
The engine at the bundle root is a **debug** build compiled with\n\
`--features dev-tools`: it auto-compiles `.ts` on load, hot-reloads script\n\
edits, and exposes the egui debug/inspector UI. It is not an optimized release\n\
build — `{BIN_DIR}/{release_engine}` is, and that is the engine a player\n\
distribution carries.\n\
\n\
## Check the install\n\
\n\
From this directory:\n\
\n\
```\n\
{BIN_DIR}/{tool} run\n\
```\n\
\n\
The engine boots the starter mod to its fallback menu. There are no levels yet;\n\
that is expected.\n\
\n\
## Start your game\n\
\n\
Keep your game in its own repository, with this bundle installed beside it as\n\
the engine you build with — see `docs/external-projects.md`. The starter's\n\
sources are in `{STARTER_TEMPLATE}/` for copying into a new project.\n\
\n\
Or experiment in place, inside `{mod_root}/`:\n\
\n\
1. **Edit a level** in TrenchBroom using `sdk/TrenchBroom/postretro.fgd` and\n\
   `sdk/TrenchBroom/GameConfig.cfg`, saved as `{mod_root}/maps/<name>.map`.\n\
2. **Compile the level**:\n\
   `{BIN_DIR}/{prl_build} {mod_root}/maps/<name>.map --baked-root baked \\\n\
   --cache-dir .build-caches/prl-cache -o {mod_root}/maps/<name>.prl`.\n\
   `--baked-root` is what keeps the compiled `.prm` sidecars where the engine\n\
   reads them; omitting it degrades every world texture to a placeholder with a\n\
   warning rather than an error.\n\
3. **Edit scripts** in TypeScript against `sdk/types/` and `sdk/lib/`. The\n\
   debug engine auto-compiles `.ts` on load and hot-reloads edits, so you can\n\
   usually skip a manual compile. To compile by hand:\n\
   `{BIN_DIR}/{scripts_build} --in {mod_root}/start-script.ts --out {mod_root}/start-script.js`.\n\
4. **Run a level**: `{BIN_DIR}/{tool} run maps/<name>.prl`. The path is\n\
   relative to the mod folder.\n\
\n\
Rename `[package].name` in `postretro.toml` before you release anything. The\n\
package name is where its players' settings and saves live, so renaming it\n\
after release strands them.\n\
\n\
## Build a player distribution\n\
\n\
From a project root:\n\
\n\
```\n\
{BIN_DIR}/{tool} dist\n\
```\n\
\n\
It bakes every level the mod's entry script names in its `maps` catalog,\n\
assembles a payload under `dist/<name>/`, and writes a launcher beside the\n\
release engine. No cargo, no repository, no toolchain — the tool runs the\n\
binaries already in `{BIN_DIR}/`. See `docs/distribution.md`.\n\
\n\
## Further reading\n\
\n\
- `docs/modding.md` — start here: what a mod is and how its pieces fit.\n\
- `docs/external-projects.md` — keeping your game in your own repository.\n\
- `docs/level_design.md` — level authoring and the compiler pipeline.\n\
- `docs/scripting-reference.md` — the scripting API surface.\n\
- `docs/weapon-mounts.md` — weapon mount and viewmodel authoring.\n\
- `docs/character-animation.md` — shared clip libraries for characters.\n\
- `docs/teleporters.md` — classic and seamless teleporters.\n\
- `docs/level-seams.md` — joining two maps with a level seam.\n\
- `docs/ghost-links.md` — seeing another room copy through a ghost link.\n\
- `docs/diagnostics.md` — diagnosing and profiling a running session.\n\
- `tools/` — Python asset helpers. See `tools/README.md` for the Python and\n\
  library requirements they need.\n\
- `docs/distribution.md` — producing a lean, shippable **player** build.\n\
\n\
The engine binary name on this host is `{engine_binary}`.\n"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn readme_covers_the_install_check_the_starter_and_shipping() {
        let readme = render_readme();
        for needle in [
            "no game\ncontent",
            "starter project",
            "content/base/",
            "sdk/templates/starter/",
            "Check the install",
            "Start your game",
            "Build a player distribution",
            "postretro-sdk",
            "Rename `[package].name`",
            "host-native",
            "dev-tools",
            "hot-reloads",
            "postretro.toml",
            "sdk/TrenchBroom/postretro.fgd",
            "GameConfig.cfg",
            "prl-build",
            "scripts-build",
            "postretro-tool",
            "--baked-root",
            "content/base/maps/<name>.prl",
            "docs/external-projects.md",
            "docs/level_design.md",
            "docs/scripting-reference.md",
            "docs/distribution.md",
            "tools/",
        ] {
            assert!(readme.contains(needle), "README missing {needle:?}");
        }
    }

    /// The bundle's docs are read by someone with no cargo. An instruction they
    /// cannot follow is a defect.
    #[test]
    fn readme_never_tells_its_reader_to_run_cargo() {
        let readme = render_readme();
        assert!(!readme.contains("cargo run"), "{readme}");
        assert!(!readme.contains("cargo build"), "{readme}");
    }

    /// The bundle ships no game content, so its README must not promise any.
    #[test]
    fn readme_promises_no_shipped_content() {
        let readme = render_readme();
        for stale in ["content-complete", "playable out of the box", "content/dev"] {
            assert!(!readme.contains(stale), "README still says {stale:?}");
        }
    }
}
